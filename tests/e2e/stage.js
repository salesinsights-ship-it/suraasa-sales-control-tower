// The Stage dropdown: five plain choices that set the status, in the task panel and the edit form.
const { chromium } = require('playwright');
const { backend, page } = require('./harness');
const results = []; const ok = (n, c, x) => results.push([c ? 'PASS' : 'FAIL', n + (x ? ' :: ' + x : '')]);
const wait = (p, ms) => p.waitForTimeout(ms || 250);
const srv = (b, s) => b.post(Object.assign({ action: 'pull' }, s ? { session: s } : {})).state;
const settle = async p => { await wait(p, 200); await p.evaluate(() => SYNC.flush()); await wait(p, 250); };
const openT = async (p, id) => { await p.evaluate(id => { const el = document.createElement('button'); el.dataset.act = 'open-task'; el.dataset.id = id; document.body.appendChild(el); el.click(); el.remove(); }, id); await wait(p); };
const pick = async (p, stage, note) => { await p.selectOption('#tu-stage', stage); if (note) await p.fill('#tu-text', note); await p.click('[data-act="tu-save"]'); await settle(p); };
(async () => {
  const br = await chromium.launch();
  const b = backend(false); const t = srv(b).tasks.find(x => x.status === 'Not Started' && !x.requiresReview);
  const p = await page(br, b);
  await openT(p, t.id);
  ok('the five stages are offered, in order', (await p.$$eval('#tu-stage option', o => o.map(x => x.textContent).join(', '))) === 'Not yet started, Moved ahead, Completed, Parked, Dropped');
  ok('it starts on the task\'s real stage', (await p.inputValue('#tu-stage')) === 'Not yet started');
  await p.selectOption('#tu-stage', 'Parked');
  ok('choosing a stage moves the Status dropdown with it', (await p.inputValue('#tu-status')) === 'On Hold');
  await p.selectOption('#tu-status', 'In Progress');
  ok('choosing a status moves the Stage dropdown with it', (await p.inputValue('#tu-stage')) === 'Moved ahead');
  await pick(p, 'Moved ahead');
  ok('Moved ahead saves as In Progress', srv(b).tasks.find(x => x.id === t.id).status === 'In Progress');
  ok('the panel shows the new stage', /Stage\s*Moved ahead/.test(await p.innerText('#modal')));
  await pick(p, 'Parked');
  ok('Parked saves as On Hold', srv(b).tasks.find(x => x.id === t.id).status === 'On Hold');
  await pick(p, 'Completed');
  let r = srv(b).tasks.find(x => x.id === t.id);
  ok('a parked task can go straight to Completed, at 100%', r.status === 'Completed' && +r.progress === 100 && !!r.completedAt);
  await pick(p, 'Not yet started');
  r = srv(b).tasks.find(x => x.id === t.id);
  ok('Not yet started clears the finish date and progress', r.status === 'Not Started' && !r.completedAt && !+r.progress, JSON.stringify([r.status, r.progress]));
  await pick(p, 'Dropped');
  ok('Dropped needs a reason', /reason/i.test(await p.textContent('#tu-err')), await p.textContent('#tu-err'));
  await pick(p, 'Dropped', 'No longer needed');
  r = srv(b).tasks.find(x => x.id === t.id);
  ok('Dropped saves as Cancelled with the reason', r.status === 'Cancelled' && r.cancelReason === 'No longer needed');
  await p.click('[data-act="close-modal"]'); await wait(p);
  await p.click('#nav [data-v="tasks"]'); await wait(p);
  ok('dropped tasks have a place to be found', !!(await p.$('[data-act="tfilter"][data-f="dropped"]')));
  await p.click('[data-act="tfilter"][data-f="dropped"]'); await wait(p);
  ok('and show there', (await p.innerText('#main')).includes(t.name));
  await openT(p, t.id);
  await pick(p, 'Moved ahead');
  ok('a dropped task can be brought back', srv(b).tasks.find(x => x.id === t.id).status === 'In Progress');
  await pick(p, 'Parked'); await p.click('[data-act="close-modal"]'); await wait(p);
  await p.click('[data-act="tfilter"][data-f="parked"]'); await wait(p);
  ok('parked tasks have their own filter', (await p.innerText('#main')).includes(t.name));
  await p.click('[data-act="tview"][data-tab="board"]'); await wait(p);
  ok('the board has a column for them', await p.evaluate(id => !!document.querySelector('[data-drop="On Hold"] [data-id="' + id + '"]'), t.id));
  await p.click('[data-act="tview"][data-tab="list"]'); await wait(p);
  // edit form
  await openT(p, t.id); await p.click('#modal [data-act="edit-task"]'); await wait(p);
  ok('the edit form has the same row', (await p.inputValue('#modal [name="stage"]')) === 'Parked');
  await p.selectOption('#modal [name="stage"]', 'Moved ahead');
  ok('and it moves Status too', (await p.inputValue('#modal [name="status"]')) === 'In Progress');
  await p.click('#modal .mf .btn.primary'); await settle(p);
  ok('the form saves the stage', srv(b).tasks.find(x => x.id === t.id).status === 'In Progress');
  await openT(p, t.id); await p.click('#modal [data-act="edit-task"]'); await wait(p);
  await p.selectOption('#modal [name="stage"]', 'Dropped'); await p.click('#modal .mf .btn.primary'); await wait(p);
  ok('the form asks why it was dropped', /reason/i.test(await p.textContent('#ferr')));
  await p.fill('#modal [name="reason"]', 'Budget cut'); await p.click('#modal .mf .btn.primary'); await settle(p);
  r = srv(b).tasks.find(x => x.id === t.id);
  ok('and records it', r.status === 'Cancelled' && r.cancelReason === 'Budget cut' && true);
  ok('stage is not stored as a second field', !('stage' in r));
  await p.click('.page-h [data-act="add-task"]'); await wait(p);
  await p.fill('#modal [name="name"]', 'Stage new task'); await p.selectOption('#modal [name="stage"]', 'Moved ahead'); await p.click('#modal .mf .btn.primary'); await settle(p);
  ok('a new task can start at a stage', srv(b).tasks.find(x => x.name === 'Stage new task').status === 'In Progress');
  ok('every change is in the audit log', srv(b).audit.filter(a => a.entityId === t.id && a.action === 'status_changed').length >= 8);
  ok('no page errors', !p.errs.length, p.errs.join('|'));
  await p.context().close();
  // review and rights still hold
  {
    const s = backend(true); const ad = s.sessionFor('admin@suraasa.com').session, ak = s.sessionFor('ak@suraasa.com').session, v = s.sessionFor('view@suraasa.com').session;
    const st = srv(s, ad); const k = st.tasks.find(x => x.owner === 'AK' && x.status === 'Not Started'); const pj = st.projects.find(x => x.id === k.projectId);
    s.post({ action: 'apply', session: ad, ops: [{ c: 'projects', id: pj.id, set: { owner: 'Head of Sales', accountable: 'Head of Sales' }, base: { owner: pj.owner, accountable: pj.accountable } }, { c: 'tasks', id: k.id, set: { requiresReview: true, status: 'In Progress' }, base: { status: k.status } }] });
    const q = await page(br, s, { session: ak }); await openT(q, k.id);
    await pick(q, 'Completed');
    ok('a task needing review cannot skip it through Stage', /review|approve/i.test(await q.textContent('#tu-err')) && srv(s, ad).tasks.find(x => x.id === k.id).status !== 'Completed', await q.textContent('#tu-err'));
    await q.selectOption('#tu-stage', 'Parked'); await q.click('[data-act="tu-save"]'); await settle(q);
    ok('the task owner can use the stages', srv(s, ad).tasks.find(x => x.id === k.id).status === 'On Hold');
    const w = await page(br, s, { session: v }); await openT(w, k.id);
    ok('a viewer sees the stage but cannot change it', !(await w.$('#tu-stage')) && /Stage\s*Parked/.test(await w.innerText('#modal')));
    await q.context().close(); await w.context().close();
  }
  await br.close();
  for (const r2 of results) console.log(r2[0], r2[1]);
  console.log(results.filter(r2 => r2[0] === 'PASS').length + ' of ' + results.length + ' passed');
  if (results.some(r2 => r2[0] === 'FAIL')) process.exitCode = 1;
})().catch(e => { for (const r2 of results) console.log(r2[0], r2[1]); console.error(String(e).slice(0, 900)); process.exit(1); });
